# ─── 主流程 ───
def main():
    # 读出CSV
    rows = []
    with open(CSV_PATH, "r", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        for r in reader:
            rows.append(r)

    print(f"读取CSV: {len(rows)} 条记录")

    # 统计频次
    stock_count = Counter()
    stock_names = {}
    fund_map = {}  # code -> {name, funds: [{fund_code, fund_name}]}
    for r in rows:
        sc = r["股票代码"].strip()
        sn = r["股票名称"].strip()
        fc = r["基金代码"].strip()
        fn = r["基金名称"].strip()
        if not sc:
            continue
        stock_count[sc] += 1
        stock_names[sc] = sn
        if sc not in fund_map:
            fund_map[sc] = {"name": sn, "funds": []}
        fund_map[sc]["funds"].append({"code": fc, "name": fn})

    print(f"不同股票数: {len(stock_count)}")

    # 分类
    boards = {"主板": [], "创业板": [], "科创板": [], "港股": []}
    for sc, cnt in stock_count.most_common():
        board = classify(sc)
        if board not in boards:
            board = "港股"  # fallback
        sn = stock_names.get(sc, "")
        intro = get_intro(sc, sn)
        # 该股票被哪些基金持有
        holding_funds = fund_map.get(sc, {}).get("funds", [])
        boards[board].append({
            "code": sc,
            "name": sn,
            "count": cnt,
            "intro": intro,
            "funds": holding_funds,
        })

    # 过滤>=3次，每板块取Top10
    result = {"date": __import__("datetime").datetime.now().strftime("%Y-%m-%d %H:%M")}
    for board_name in ("主板", "创业板", "科创板", "港股"):
        items = [x for x in boards[board_name] if x["count"] >= 3]
        top10 = items[:10]
        print(f"\n{'─' * 50}")
        print(f"【{board_name}】共 {len(items)} 只 >=3次, 展示 Top{len(top10)}")
        print(f"{'代码':<10} {'名称':<14} {'次数':<6} {'简介'}")
        print(f"{'─' * 50}")
        for item in top10:
            print(f"{item['code']:<10} {item['name']:<14} x{item['count']:<5} {item['intro']}")
        result[board_name] = top10

    # 保存JSON
    json_path = OUTPUT_JSON
    os.makedirs(os.path.dirname(json_path), exist_ok=True)
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(result, f, ensure_ascii=False, indent=2)
    print(f"\n已保存 JSON: {json_path}")

