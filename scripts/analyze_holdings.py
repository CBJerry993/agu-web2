def classify(code: str) -> str:
    """按代码前缀分类板块"""
    s = str(code).strip()
    if not s:
        return "其他"
    # 港股/美股 (含字母)
    if re.match(r'^[A-Za-z]', s):
        return "港股"
    if s.startswith("688"):
        return "科创板"
    if s.startswith(("300", "301")):
        return "创业板"
    if s.startswith(("600", "601", "603", "605", "000", "001", "002", "003")):
        return "主板"
    return "其他"


